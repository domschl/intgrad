import json
import re

from intgrad.corpus import ingest


def test_unwrap_joins_hard_wrapped_prose_and_hyphenation():
    para = ("This paragraph was wrapped by a converter at a fixed width so that\n"
            "every line ends early and the words continue on the next line hy-\n"
            "phenated in the middle of a word, and then the paragraph just ends.")
    out = ingest.clean_markdown(para + "\n\nNext paragraph.")
    first = out.split("\n\n")[0]
    assert "\n" not in first and "hyphenated" in first and "hy- " not in first and out.endswith("Next paragraph.")


def test_verse_lists_code_and_tables_are_not_unwrapped():
    verse = "Short line\nanother one that is much longer than the first\nend"
    lst = "- one item that is fairly long and keeps going\n- another item that is long"
    code = "```\nx = 1\ny = 2\n```"
    table = "| a  |   b |\n|:---|----:|\n| 1  |   2 |"
    out = ingest.clean_markdown("\n\n".join([verse, lst, code, table]))
    assert "Short line\nanother" in out and "\n- another" in out and "x = 1\ny = 2" in out
    assert "| a | b |\n|---|\n| 1 | 2 |" in out


def test_images_and_link_targets_are_dropped():
    out = ingest.clean_markdown("See ![fig](img.png) the [manual](http://x.org/m \"t\") now.�")
    assert out == "See  the manual now."


def test_code_filters():
    good = "def f(x):\n    return x + 1\n" * 10
    assert ingest.code_ok(good, "a/b.py", "python")
    assert not ingest.code_ok("x" * 2000, "a.min.js", "javascript")              # one long line
    assert not ingest.code_ok("// Code generated by tool. DO NOT EDIT.\n" + good, "g.go", "go")
    assert not ingest.code_ok(good, "web/package-lock.json", "json")
    assert not ingest.code_ok('{"k": 1}\n' * 2000, "big.json", "json")           # data-like size cap
    assert ingest.redact("mail a.b@example.org at 10.0.0.1") == "mail <EMAIL> at <IP_ADDRESS>"


def _calls(doc: str) -> list:
    return [json.loads(m) for m in re.findall(r"<tool_call>\n(.*?)\n</tool_call>", doc, re.S)]


def test_glaive_string_arguments_become_json():
    system = ('SYSTEM: You can use these functions -\n'
              '{"name": "f", "parameters": {"type": "object"}}')
    chat = ("USER: hi\n\n\nASSISTANT: <functioncall> "
            "{\"name\": \"f\", \"arguments\": '{\"a\": 1}'} <|endoftext|>\n\n\n"
            "FUNCTION RESPONSE: {\"ok\": true}\n\n\nASSISTANT: done <|endoftext|>")
    doc = ingest.render_glaive(system, chat)
    assert _calls(doc) == [{"name": "f", "arguments": {"a": 1}}]
    assert doc.index("<tools>") < doc.index("<user>") < doc.index("<tool_response>")
    assert "<|endoftext|>" not in doc and doc.rstrip().endswith("done\n</assistant>")


def test_xlam_and_hermes_render_the_same_format():
    x = ingest.render_xlam("q?", '[{"name": "g", "parameters": {}}]',
                           '[{"name": "g", "arguments": {"b": "c"}}]')
    assert _calls(x) == [{"name": "g", "arguments": {"b": "c"}}] and "<user>\nq?\n</user>" in x
    h = ingest.render_hermes([{"from": "human", "value": "q?"},
                              {"from": "gpt", "value": '<tool_call>\n{"name": "g", "arguments": {}}\n</tool_call>'},
                              {"from": "tool", "value": "<tool_response>\n{}\n</tool_response>"}])
    assert _calls(h) == [{"name": "g", "arguments": {}}]
    assert h.count("<tool_response>") == 1
